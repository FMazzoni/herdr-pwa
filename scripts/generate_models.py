#!/usr/bin/env python3
"""Regenerate the committed Pydantic models from herdr's own JSON Schema."""

import argparse
import difflib
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
import warnings
from pathlib import Path
from types import MappingProxyType
from typing import Any, Final

from datamodel_code_generator import (
    DataModelType,
    Formatter,
    InputFileType,
    PythonVersion,
)
from datamodel_code_generator import generate as codegen

ROOT: Final = Path(__file__).resolve().parent.parent
SCHEMA_PATH: Final = ROOT / "tests" / "fixtures" / "herdr-api-schema.json"
OUT_DIR: Final = ROOT / "src" / "herdr_pwa" / "engine" / "generated"

# Sub-schemas to generate, in the order they are written.
SUB_SCHEMAS: Final = (
    "success_response",
    "event",
    "subscription_event",
    "error_response",
    "request",
)

# Properties that act as a oneOf discriminator, most specific first.
DISCRIMINATORS: Final = ("type", "method", "event", "kind")

# Passed to datamodel_code_generator.generate() in this interpreter; ruff formats its output.
CODEGEN_OPTIONS: Final = MappingProxyType(
    {
        "input_file_type": InputFileType.JsonSchema,
        "output_model_type": DataModelType.PydanticV2BaseModel,
        "target_python_version": PythonVersion.PY_313,
        "use_title_as_name": True,
        "field_constraints": True,
        "use_annotated": True,
        "use_standard_collections": True,
        "use_union_operator": True,
        "use_schema_description": True,
        "disable_timestamp": True,
        # Format only: the CLI this replaced took `--formatters ruff-check --formatters ruff-format`,
        # where the last flag wins, and the committed models are what that produced.
        "formatters": [Formatter.RUFF_FORMAT],
    }
)


def capture_schema() -> None:
    """Re-vendor ``herdr api schema --json`` into tests/fixtures/."""
    raw = subprocess.run(
        ["herdr", "api", "schema", "--json"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    doc = json.loads(raw)
    # Pretty-printed and key-sorted: the point of vendoring is that the *next*
    # upgrade produces a readable diff, and herdr emits one long line.
    SCHEMA_PATH.write_text(
        json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    sys.stdout.write(
        f"captured {SCHEMA_PATH.relative_to(ROOT)} "
        f"(protocol {doc['protocol']}, schema_version {doc['schema_version']})\n"
    )


def _pascal(value: str) -> str:
    """``pane.agent_status_changed`` -> ``PaneAgentStatusChanged``."""
    return "".join(part.capitalize() for part in re.split(r"[^A-Za-z0-9]+", value) if part)


def _title_members(node: dict[str, Any], parent: str) -> None:
    """Title each untitled ``oneOf``/``anyOf`` member after its discriminator."""
    for keyword in ("oneOf", "anyOf"):
        for member in node.get(keyword, []):
            if not isinstance(member, dict) or "title" in member:
                continue
            props = member.get("properties")
            if not isinstance(props, dict):
                continue
            for disc in DISCRIMINATORS:
                const = (props.get(disc) or {}).get("const")
                if isinstance(const, str):
                    member["title"] = _pascal(const) + parent
                    break


def _name_variants(node: object, parent: str) -> None:
    """Give every discriminated ``oneOf``/``anyOf`` member a stable ``title``."""
    if isinstance(node, list):
        for item in node:
            _name_variants(item, parent)
        return
    if not isinstance(node, dict):
        return

    _title_members(node, parent)

    for key, value in node.items():
        if key == "$defs" and isinstance(value, dict):
            # A new naming scope: each definition names the unions inside it.
            for def_name, def_body in value.items():
                _name_variants(def_body, def_name)
        else:
            _name_variants(value, parent)


def split(doc: dict[str, Any], name: str) -> dict[str, Any]:
    """One sub-schema as a standalone document, refs rewritten and named."""
    text = json.dumps(doc["schemas"][name])
    text = text.replace(f"#/schemas/{name}/$defs/", "#/$defs/")
    sub = json.loads(text)
    if "#/schemas/" in json.dumps(sub):
        raise SystemExit(f"{name}: cross-sub-schema $ref — the split is not lossless")
    _name_variants(sub, sub.get("title", _pascal(name)))
    return sub


def _header(name: str, digest: str, doc: dict[str, Any]) -> str:
    return (
        "# @generated by scripts/generate_models.py — DO NOT EDIT BY HAND.\n"
        "#\n"
        f"# source:         herdr api schema --json -> schemas.{name}\n"
        f"# vendored at:    tests/fixtures/{SCHEMA_PATH.name}\n"
        f"# protocol:       {doc['protocol']}\n"
        f"# schema_version: {doc['schema_version']}\n"
        f"# schema sha256:  {digest}\n"
        "#\n"
        "# Regenerate with:  uv run python scripts/generate_models.py\n"
        "# ruff: noqa\n"
    )


def generate(out_dir: Path) -> None:
    """Write the generated package into ``out_dir``."""
    raw = SCHEMA_PATH.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    doc = json.loads(raw)

    out_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        tmpdir = Path(tmp)
        for name in SUB_SCHEMAS:
            # The input filename lands in the generator's own header comment,
            # so it has to be stable across machines: name it after the schema.
            src = tmpdir / f"{name}.json"
            src.write_text(json.dumps(split(doc, name), indent=1), encoding="utf-8")
            dst = tmpdir / f"{name}.py"
            # Ruff reads its config from here: the scratch dir, so this repo's ruff.toml never applies.
            with warnings.catch_warnings():
                # herdr's unsigned formats (uint64...) map to int, as the CLI did, whose stderr went unread.
                warnings.filterwarnings("ignore", r"format of '\w+' not understood", UserWarning)
                codegen(src, output=dst, settings_path=tmpdir, **CODEGEN_OPTIONS)
            body = dst.read_text(encoding="utf-8")
            # Drop the generator's own two-line provenance header; ours says more.
            body = re.sub(r"\A# generated by datamodel-codegen:\n(?:#.*\n)*", "", body)
            (out_dir / f"{name}.py").write_text(
                _header(name, digest, doc) + "\n" + body, encoding="utf-8"
            )

    (out_dir / "__init__.py").write_text(_init_module(digest, doc), encoding="utf-8")


def _init_module(digest: str, doc: dict[str, Any]) -> str:
    """The package facade."""
    return f'''\
"""Pydantic models generated from herdr's published JSON Schema.

@generated by scripts/generate_models.py — DO NOT EDIT BY HAND.
protocol {doc["protocol"]}, schema_version {doc["schema_version"]}.

These describe herdr's **wire**. The hand-written models in
:mod:`herdr_pwa.engine.model` describe what the phone needs; they are a thin
layer over this one, never a replacement for it. Import the wire types here,
normalize once at the boundary, and hand the templates the hand-written shapes.

Only the read path is re-exported. The request/event modules are importable
directly (``from herdr_pwa.engine.generated import request``) so that ~90
command types cannot drift into a template by autocomplete.
"""

from __future__ import annotations

from herdr_pwa.engine.generated.error_response import ErrorBody, ErrorResponse
from herdr_pwa.engine.generated.success_response import (
    AgentInfo,
    AgentSessionInfo,
    AgentStatus,
    PaneInfo,
    SessionSnapshot,
    SessionSnapshotResponseResult,
    SuccessResponse,
    TabInfo,
    WorkspaceInfo,
)

#: The protocol the vendored schema was captured at. Compare against
#: :data:`herdr_pwa.engine.model.EXPECTED_PROTOCOL`.
SCHEMA_PROTOCOL = {doc["protocol"]}
SCHEMA_VERSION = {doc["schema_version"]}
SCHEMA_SHA256 = "{digest}"

__all__ = [
    "SCHEMA_PROTOCOL",
    "SCHEMA_SHA256",
    "SCHEMA_VERSION",
    "AgentInfo",
    "AgentSessionInfo",
    "AgentStatus",
    "ErrorBody",
    "ErrorResponse",
    "PaneInfo",
    "SessionSnapshot",
    "SessionSnapshotResponseResult",
    "SuccessResponse",
    "TabInfo",
    "WorkspaceInfo",
]
'''


def check() -> int:
    """Regenerate into a temp dir and diff against the committed package."""
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "generated"
        generate(fresh)
        stale = []
        names = sorted(
            {p.name for p in fresh.glob("*.py")} | {p.name for p in OUT_DIR.glob("*.py")}
        )
        for name in names:
            want = (fresh / name).read_text(encoding="utf-8") if (fresh / name).exists() else ""
            have = (OUT_DIR / name).read_text(encoding="utf-8") if (OUT_DIR / name).exists() else ""
            if want != have:
                stale.append(name)
                sys.stdout.writelines(
                    difflib.unified_diff(
                        have.splitlines(True),
                        want.splitlines(True),
                        fromfile=f"committed/{name}",
                        tofile=f"regenerated/{name}",
                    )
                )
    if stale:
        sys.stdout.write(
            f"\nSTALE: {', '.join(stale)} — run: uv run python scripts/generate_models.py\n"
        )
        return 1
    sys.stdout.write("generated models are up to date\n")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--capture",
        action="store_true",
        help="re-vendor the schema from a live herdr first",
    )
    parser.add_argument(
        "--check", action="store_true", help="fail if the committed output is stale"
    )
    args = parser.parse_args()

    if args.capture:
        if shutil.which("herdr") is None:
            raise SystemExit("--capture needs `herdr` on PATH")
        capture_schema()
    if args.check:
        return check()
    generate(OUT_DIR)
    sys.stdout.write(f"wrote {OUT_DIR.relative_to(ROOT)}/\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
